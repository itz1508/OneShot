async (page) => {
  const passed = [];
  const check = (condition, name) => { if (!condition) throw new Error(name); passed.push(name); };
  page.setDefaultTimeout(8000);
  await page.setViewportSize({width:1536,height:960});
  await page.reload();
  await page.getByRole('button',{name:'Open workflow-diagram.png',exact:true}).waitFor();
  check(await page.locator('.panel:visible').count() === 4, 'Desktop has four visible product zones');
  check(await page.locator('#source-count').textContent() === '7', 'All seven supplied references loaded');
  await page.getByRole('button',{name:'Open workflow-diagram.png',exact:true}).click();
  await page.locator('#source-image').waitFor();
  await page.waitForFunction(()=>document.querySelector('#source-image')?.naturalWidth>0);
  check(await page.locator('#source-image').evaluate(el=>el.naturalWidth) === 3112, 'Original workflow PNG is decoded at full resolution');
  await page.getByRole('button',{name:'Expand image',exact:true}).click();
  check(await page.locator('#image-dialog').isVisible(), 'Image expands into an accessible dialog');
  await page.getByRole('button',{name:'Close expanded image',exact:true}).click();
  await page.getByRole('button',{name:'Add source',exact:true}).click();
  const baseline = '# Verification notes\n\n' + Array.from({length:100},(_,i)=>`Line ${i+1}: source content for revision recovery.`).join('\n');
  await page.getByRole('textbox',{name:'New source name',exact:true}).fill('verification-notes.md');
  await page.getByRole('textbox',{name:'New source content',exact:true}).fill(baseline);
  await page.getByRole('button',{name:'Create source',exact:true}).click();
  await page.getByRole('heading',{name:'verification-notes.md',exact:true}).waitFor();
  const all = page.getByRole('checkbox',{name:'Select visible',exact:true});
  await all.check(); await all.uncheck();
  await page.getByRole('checkbox',{name:'Select verification-notes.md',exact:true}).check();
  await page.getByRole('textbox',{name:'Agent conversation draft',exact:true}).fill('Agent draft must stay independent.');
  await page.getByRole('textbox',{name:'Preparation instruction',exact:true}).fill('System note must survive preparation.');
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  const editor = page.getByRole('textbox',{name:'Edit source working revision',exact:true});
  const draft = baseline + '\nUNSAVED_SENTINEL';
  await editor.fill(draft);
  await editor.evaluate(el=>{el.setSelectionRange(24,31);el.scrollTop=180;el.dispatchEvent(new Event('click'));});
  const before = await editor.evaluate(el=>({start:el.selectionStart,end:el.selectionEnd,scroll:el.scrollTop}));
  await page.getByRole('button',{name:'Start preparation',exact:true}).click();
  await page.getByRole('button',{name:'Return to review',exact:true}).waitFor();
  check(await page.locator('#process-view').isVisible() && !await page.locator('#review-view').isVisible(), 'Start swaps only detail slot to processing');
  check(await page.getByRole('textbox',{name:'Agent conversation draft',exact:true}).inputValue() === 'Agent draft must stay independent.', 'Agent draft preserved and no automatic agent response');
  check(await page.getByRole('textbox',{name:'Preparation instruction',exact:true}).inputValue() === 'System note must survive preparation.', 'System draft preserved');
  check(await page.locator('#process-state').textContent() === 'partial', 'Local processing reports partial semantic coverage');
  check(await page.getByRole('button',{name:'Start preparation',exact:true}).isDisabled(), 'New preparation waits for terminal acknowledgment');
  await page.getByRole('button',{name:'Return to review',exact:true}).click();
  check(await editor.inputValue() === draft, 'Unsaved editor draft restored');
  const after = await editor.evaluate(el=>({start:el.selectionStart,end:el.selectionEnd,scroll:el.scrollTop}));
  check(JSON.stringify(before) === JSON.stringify(after), 'Editor selection and scroll restored');
  await page.getByRole('button',{name:'Diff review',exact:true}).click();
  check((await page.locator('#diff-content').textContent()).includes('UNSAVED_SENTINEL'), 'Diff displays actual working revision change');
  await page.screenshot({path:'output/playwright/diff-review.png'});
  await page.getByRole('button',{name:'Save revision',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#revision-status')?.textContent==='Saved revision');
  await page.reload();
  await page.getByRole('heading',{name:'verification-notes.md',exact:true}).waitFor();
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  check(await editor.inputValue() === draft, 'IndexedDB restores saved revision after reload');
  check(await page.getByRole('textbox',{name:'Agent conversation draft',exact:true}).inputValue() === 'Agent draft must stay independent.', 'IndexedDB restores independent chat draft');
  await page.locator('#prepared-list [data-result]').first().click();
  const report = await page.locator('#read-content').textContent();
  check(!report.includes('UNSAVED_SENTINEL'), 'Prepared result used saved snapshot and excluded unsaved draft');
  check(report.includes('semantic') && report.includes('unavailable'), 'Prepared report describes actual processing limitations');
  await page.getByRole('button',{name:'Activity history',exact:true}).click();
  check(await page.locator('.history-run').count() === 1, 'Completed operation is retained in history');
  await page.getByRole('button',{name:'Close activity history',exact:true}).click();
  await page.getByRole('button',{name:'Open command menu',exact:true}).click();
  await page.getByRole('textbox',{name:'Search commands',exact:true}).fill('state-driven');
  await page.locator('[data-command-file]').click();
  await page.waitForFunction(()=>document.querySelector('#source-image')?.naturalWidth>0);
  check((await page.locator('#file-title').textContent()) === 'state-driven-transition.png', 'Command search opens second supplied PNG');
  await page.getByRole('button',{name:'Open workflow-diagram.png',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#source-image')?.naturalWidth>0);
  await page.screenshot({path:'output/playwright/desktop-verified.png'});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'Desktop has no horizontal document overflow');
  return {passed};
}
