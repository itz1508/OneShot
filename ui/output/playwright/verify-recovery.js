async (page) => {
  const passed = [];
  const check = (condition,name)=>{if(!condition)throw new Error(name);passed.push(name);};
  page.setDefaultTimeout(10000);
  await page.setViewportSize({width:1536,height:960});
  await page.reload();
  await page.getByRole('button',{name:'Open workflow-diagram.png',exact:true}).waitFor();
  await page.locator('#folder-input').setInputFiles('output/playwright/fixtures');
  await page.getByRole('heading',{name:'folder-note.md',exact:true}).waitFor();
  check((await page.locator('#file-breadcrumb').textContent()).includes('fixtures / nested'),'Folder import retains nested source paths');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button',{name:'Download working revision',exact:true}).click();
  const downloaded = await downloadPromise;
  check(downloaded.suggestedFilename()==='folder-note.md','Revision download uses the selected source filename');
  await downloaded.saveAs('output/playwright/downloaded-folder-note.md');
  const all = page.getByRole('checkbox',{name:'Select visible',exact:true});
  await all.check(); await all.uncheck();
  await page.getByRole('checkbox',{name:'Select pause-check-1.txt',exact:true}).check();
  await page.getByRole('button',{name:'Start preparation',exact:true}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#process-state').textContent==='paused');
  await page.waitForFunction(()=>document.querySelector('#save-status').textContent==='Workspace saved in this browser');
  page.once('dialog',dialog=>dialog.accept());
  await page.reload();
  await page.getByRole('button',{name:'Activity history',exact:true}).click();
  await page.getByRole('heading',{name:/Interrupted preparation/}).waitFor();
  check(true,'Reloaded paused run becomes interrupted history, without fabricated completion');
  await page.getByRole('button',{name:'Close activity history',exact:true}).click();
  const sourceCount = await page.locator('#source-count').textContent();
  await page.addInitScript(()=>{
    if(sessionStorage.getItem('oneshot-read-failure-injected'))return;
    sessionStorage.setItem('oneshot-read-failure-injected','yes');
    window.__verificationWrites=0;
    const originalPut=IDBObjectStore.prototype.put;
    IDBObjectStore.prototype.put=function(...args){window.__verificationWrites++;return originalPut.apply(this,args);};
    IDBObjectStore.prototype.get=function(){throw new Error('Injected workspace read failure');};
  });
  await page.reload();
  await page.getByRole('button',{name:'Retry loading',exact:true}).waitFor();
  check(await page.evaluate(()=>window.__verificationWrites)===0,'Failed workspace read causes no default-data write');
  check(await page.locator('#workbench').evaluate(el=>el.inert),'Failed workspace read keeps mutation controls unavailable');
  await page.getByRole('button',{name:'Retry loading',exact:true}).click();
  await page.getByRole('button',{name:'Open workflow-diagram.png',exact:true}).waitFor();
  check(await page.locator('#source-count').textContent()===sourceCount,'Retry recovers the existing sources after a transient read failure');
  await page.getByRole('button',{name:'Open workflow-diagram.png',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#source-image')?.naturalWidth>0);
  await page.getByRole('button',{name:'Switch color theme',exact:true}).click();
  check(await page.evaluate(()=>getComputedStyle(document.body).color)==='rgb(235, 236, 226)','Dark theme applies readable foreground color');
  await page.locator('#toast').waitFor({state:'hidden'});
  await page.screenshot({path:'output/playwright/desktop-dark.png'});
  await page.getByRole('button',{name:'Switch color theme',exact:true}).click();
  await page.setViewportSize({width:1180,height:850});
  check(await page.locator('.panel:visible').count()===3,'Standard desktop collapses the auxiliary system panel');
  await page.getByRole('button',{name:'System',exact:true}).click();
  check(await page.locator('#system-panel').isVisible(),'Standard desktop can reopen system context');
  await page.getByRole('button',{name:'Collapse system context',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Sources',exact:false}).first().click();
  check(await page.locator('#sources-panel').isVisible(),'Mobile sources remain reachable after desktop panel changes');
  await page.screenshot({path:'output/playwright/mobile-sources.png'});
  return {passed};
}
