async (page) => {
  const passed = [];
  const check = (condition,name)=>{if(!condition)throw new Error(name);passed.push(name);};
  page.setDefaultTimeout(12000);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  const all = page.getByRole('checkbox',{name:'Select visible',exact:true});
  await all.check(); await all.uncheck();
  const data = Buffer.from('# Browser verification source\n' + 'Actual local text to read and inspect.\n'.repeat(24000));
  await page.locator('#file-input').setInputFiles(Array.from({length:8},(_,i)=>({name:`pause-check-${i+1}.txt`,mimeType:'text/plain',buffer:data})));
  await page.getByRole('heading',{name:'pause-check-1.txt',exact:true}).waitFor();
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await page.getByRole('button',{name:'Start preparation',exact:true}).click();
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#process-state')?.textContent==='paused');
  const pausedCount = await page.locator('#process-events').textContent();
  await page.getByRole('button',{name:'Agent',exact:true}).click();
  await page.getByRole('textbox',{name:'Agent conversation draft',exact:true}).fill('Mobile agent remains independent while paused.');
  check(await page.locator('#process-events').textContent()===pausedCount,'Pause acknowledgment freezes actual file reads');
  check(await page.locator('#workbench').getAttribute('data-mobile-view')==='agent','Mobile agent can be used during paused processing');
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await page.getByRole('button',{name:'Resume',exact:true}).click();
  await page.getByRole('button',{name:'Agent',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#process-state')?.textContent==='partial',{},{timeout:30000});
  check(await page.locator('#workbench').getAttribute('data-mobile-view')==='agent','Live events and completion do not steal mobile navigation');
  check(await page.getByRole('textbox',{name:'Agent conversation draft',exact:true}).inputValue()==='Mobile agent remains independent while paused.','Mobile chat draft survives resume and completion');
  await page.getByRole('button',{name:'Review',exact:true}).click();
  await page.screenshot({path:'output/playwright/mobile-partial-result.png'});
  await page.getByRole('button',{name:'Return to review',exact:true}).click();
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await page.getByRole('button',{name:'Start preparation',exact:true}).click();
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#process-state')?.textContent==='paused');
  await page.getByRole('button',{name:'Stop',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#process-state')?.textContent==='stopped');
  check(true,'Stop finalizes a genuinely paused operation');
  await page.getByRole('button',{name:'Review',exact:true}).click();
  await page.getByRole('button',{name:'Return to review',exact:true}).click();
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await all.check(); await all.uncheck();
  await page.locator('#file-input').setInputFiles({name:'unsupported-document.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.7\nVerification fixture; no local extractor.')});
  await page.getByRole('heading',{name:'unsupported-document.pdf',exact:true}).waitFor();
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await page.getByRole('button',{name:'Start preparation',exact:true}).click();
  await page.getByRole('button',{name:'Return to review',exact:true}).waitFor();
  check(await page.locator('#process-state').textContent()==='failed','Unsupported-only input reports failed, without fabricated extraction');
  check((await page.locator('#process-findings').textContent()).includes('PDF extraction is unavailable'),'PDF limitation is visible before terminal acknowledgment');
  await page.getByRole('button',{name:'Return to review',exact:true}).click();
  await page.getByRole('button',{name:/^Sources \d+$/}).click();
  await page.getByRole('searchbox',{name:'Find a source',exact:true}).fill('workflow-diagram');
  check(await page.locator('.tree-row').count()===1,'Source search filters the actual tree');
  await page.getByRole('button',{name:'Open workflow-diagram.png',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#source-image')?.naturalWidth>0);
  check(await page.locator('.panel:visible').count()===1,'Mobile shows one product zone at a time');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile has no horizontal document overflow');
  await page.screenshot({path:'output/playwright/mobile-diagram.png'});
  await page.getByRole('button',{name:'Switch color theme',exact:true}).click();
  check(await page.locator('html').getAttribute('data-theme')==='dark','Theme control switches palette');
  await page.screenshot({path:'output/playwright/mobile-dark.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  check(await page.locator('.live-orbit').evaluate(el=>getComputedStyle(el).animationName)==='none','Reduced motion disables process animation');
  await page.getByRole('button',{name:'Switch color theme',exact:true}).click();
  return {passed};
}
